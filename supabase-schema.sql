-- Run this in Supabase Dashboard > SQL Editor.
create table if not exists public.franchise_enquiries (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null,
  email text not null,
  phone text,
  timing text not null,
  role text not null,
  area text not null,
  budget text not null,
  message text,
  language text not null default 'en'
);

-- Keep the table private. The Next.js server uses the service-role key,
-- which must never be exposed in browser code.
alter table public.franchise_enquiries enable row level security;
-- Do not create public SELECT / INSERT policies.
